export type Translate = (key: MessageKey, params?: Record<string, string | number>) => string;

const STORAGE_KEY = "linkedin-agent.locale.v1";

function interpolate(message: string, params: Record<string, string | number> = {}) {
  return message.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? `{${key}}`));
}

export function resolveInitialLocale(value: string | null): AppLocale {
  return value === "en" || value === "pt-BR" ? value : "pt-BR";
}

const I18nContext = React.createContext<{
  locale: AppLocale;
  setLocale: (locale: AppLocale) => void;
  t: Translate;
} | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocale] = React.useState<AppLocale>(() => resolveInitialLocale(localStorage.getItem(STORAGE_KEY)));

  React.useEffect(() => {
    localStorage.setItem(STORAGE_KEY, locale);
    document.documentElement.lang = locale;
  }, [locale]);

  const t = React.useCallback<Translate>(
    (key, params) => interpolate((locale === "en" ? en : ptBR)[key], params),
    [locale]
  );

  return <I18nContext.Provider value={{ locale, setLocale, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = React.useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside LanguageProvider");
  return value;
}

export function localizedError(error: unknown, t: Translate, locale: AppLocale) {
  if (error instanceof ApiError) {
    const known = `error.${error.code}` as MessageKey;
    if (known in ptBR) return t(known, error.params);
    if (locale === "pt-BR" && error.message) return error.message;
    return t("common.unknownError", { code: error.code ? ` (${error.code})` : "" });
  }
  return t("common.unknownError", { code: "" });
}

